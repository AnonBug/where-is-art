import fs from "node:fs/promises";
const tokens = JSON.parse(await fs.readFile("src/styles/tokens.json", "utf8"));
await fs.writeFile(
  "src/styles/_tokens.generated.scss",
  `// Generated by build-theme.mjs\n:root {\n${Object.entries(tokens)
    .map(([key, value]) => `  --${key}: ${value};`)
    .join("\n")}\n}\n`,
);
const style = JSON.parse(
  await fs.readFile("content/map-style-base.json", "utf8"),
);
style.name = "名画在哪里 · 青绿";
style.layers = style.layers.filter(
  (layer) =>
    layer.type !== "raster" &&
    !/poi|aeroway|aerodrome|housenumber|shield/.test(layer.id),
);
for (const layer of style.layers) {
  layer.paint ??= {};
  if (layer.type === "background")
    layer.paint["background-color"] = tokens.land;
  if (layer.type === "fill") {
    delete layer.paint["fill-pattern"];
    layer.paint["fill-color"] =
      layer["source-layer"] === "water"
        ? tokens.map
        : /building/.test(layer.id)
          ? "#DCDCC9"
          : /park|wood|grass|wetland/.test(layer.id)
            ? "#DFE4D1"
            : tokens.land;
    if (layer["source-layer"] === "building") layer.minzoom = 14;
  }
  if (layer.type === "line") {
    layer.paint["line-color"] = /water/.test(layer.id)
      ? "#C2D5CC"
      : /boundary/.test(layer.id)
        ? "#BDBDAB"
        : /casing/.test(layer.id)
          ? "#D8D4C1"
          : "#F9F5EA";
    if (/boundary/.test(layer.id)) layer.paint["line-opacity"] = 0.55;
  }
  if (layer.type === "symbol") {
    layer.layout ??= {};
    delete layer.layout["icon-image"];
    if (layer.layout["text-field"])
      layer.layout["text-field"] = [
        "coalesce",
        ["get", "name:zh"],
        ["get", "name:en"],
        ["get", "name"],
      ];
    layer.paint["text-color"] = "#738276";
    layer.paint["text-halo-color"] = tokens.paper;
    layer.paint["text-halo-width"] = 1.5;
  }
}
delete style.sources.ne2_shaded;
style.sources.openmaptiles.attribution =
  '<a href="https://openfreemap.org/" target="_blank">OpenFreeMap</a> © <a href="https://www.openmaptiles.org/" target="_blank">OpenMapTiles</a> · <a href="https://www.openstreetmap.org/copyright" target="_blank">OpenStreetMap</a>';
await fs.writeFile("public/map-style.json", JSON.stringify(style));
